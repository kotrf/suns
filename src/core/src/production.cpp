std::uint64_t reconstruction_remaining(const Planet& planet,ProductionKind kind)
{
    const auto& damage=planet.warDamage;
    const auto destroyed=kind==ProductionKind::ReconstructFactory?damage.factoriesDestroyed:damage.minesDestroyed;
    const auto rebuilt=kind==ProductionKind::ReconstructFactory?damage.factoriesReconstructed:damage.minesReconstructed;
    return reconstruction_kind(kind) && destroyed>=rebuilt ? destroyed-rebuilt : 0;
}
std::uint64_t reconstruction_available(const Planet& planet,ProductionKind kind)
{
    auto remaining=reconstruction_remaining(planet,kind);
    const auto installed=kind==ProductionKind::ReconstructFactory?planet.industry:planet.mines;
    auto room=std::uint64_t(std::numeric_limits<std::uint32_t>::max()-installed);
    for(const auto& item:planet.productionQueue) if(item.kind==kind) {
        remaining-=std::min(remaining,std::uint64_t(item.quantity));
        room-=std::min(room,std::uint64_t(item.quantity));
    }
    return std::min(remaining,room);
}

bool production_batch_valid(const QueueProductionBatchOrder& order)
{
    if (order.quantity == 0 || order.quantity > kMaximumProductionBatch) return false;
    if (engineering_kind(order.kind)) return order.quantity==1 && order.automation==ProductionAutomation::None;
    if (recovery_kind(order.kind)) return order.automation==ProductionAutomation::None;
    if (order.kind != ProductionKind::Factory && order.kind != ProductionKind::Mine
        && order.kind != ProductionKind::Terraforming && order.kind != ProductionKind::ColonyDefense
        && order.kind != ProductionKind::LocalRadar && order.kind != ProductionKind::PlanetaryRadar) return false;
    if (static_cast<unsigned>(order.automation) > static_cast<unsigned>(ProductionAutomation::MaxTerraform)) return false;
    // A planet can install at most one receiver tier at once. Annual radar
    // rules may appear in default templates; they retire when built.
    if ((order.kind == ProductionKind::LocalRadar || order.kind == ProductionKind::PlanetaryRadar)
        && order.quantity != 1) return false;
    if (order.kind == ProductionKind::Terraforming) return order.automation != ProductionAutomation::Annual;
    return order.automation == ProductionAutomation::None || order.automation == ProductionAutomation::Annual;
}

bool apply_production_batch(const GameState& state, Planet& planet, const QueueProductionBatchOrder& order)
{
    if (planet.id != order.colony || !production_batch_valid(order)) return false;
    if (engineering_kind(order.kind)) return apply_planetary_engineering_order(state,planet,
        {planet.id,engineering_project_kind(order.kind),EngineeringAction::StartOrResume,10});
    if (reconstruction_kind(order.kind) && order.quantity>reconstruction_available(planet,order.kind)) return false;
    if (order.kind==ProductionKind::CleanupContamination && order.quantity>cleanup_units_available(planet)) return false;
    if (order.kind == ProductionKind::Terraforming
        && !next_terraforming_environment(state, planet.owner, planet)) return false;
    if (order.kind == ProductionKind::ColonyDefense && !colony_defenses_available(state,planet.owner)) return false;
    if (order.kind == ProductionKind::LocalRadar && planet.radar != PlanetaryRadarLevel::None) return false;
    if (order.kind == ProductionKind::PlanetaryRadar && planet.radar == PlanetaryRadarLevel::Full) return false;
    planet.productionQueue.push_back({order.kind, production_cost(order.kind), 0,
        order.automation, order.quantity});
    return true;
}

bool production_template_valid(const ProductionTemplate& value)
{
    if (value.name.empty() || value.name.size() > 80 || value.items.empty() || value.items.size() > 64
        || std::none_of(value.name.begin(), value.name.end(), [](unsigned char c) { return !std::isspace(c); })) return false;
    return std::all_of(value.items.begin(), value.items.end(), [](const ProductionItem& item) {
        return !engineering_kind(item.kind) && !recovery_kind(item.kind) && !item.autoGenerated && item.shipDesign == 0 && !item.station
            && item.remainingCost == production_cost(item.kind)
            && production_batch_valid({0, item.kind, item.quantity, item.automation});
    });
}

std::vector<ProductionTemplate> colony_development_presets()
{
    const auto step = [](ProductionKind kind, std::uint32_t count = 1,
        ProductionAutomation mode = ProductionAutomation::None) {
        return ProductionItem{kind, production_cost(kind), 0, mode, count};
    };
    const auto radar = step(ProductionKind::LocalRadar);
    const auto factories = step(ProductionKind::Factory, 3);
    const auto mines = step(ProductionKind::Mine, 3);
    const auto annualFactories = step(ProductionKind::Factory, 3, ProductionAutomation::Annual);
    const auto annualMines = step(ProductionKind::Mine, 3, ProductionAutomation::Annual);
    return {{"Fast Link", {radar, factories, mines}},
        {"Industry First", {factories, radar, mines, annualFactories, annualMines}},
        {"Mining First", {mines, radar, factories, annualFactories, annualMines}}};
}

bool set_production_template(Player& player, const SetProductionTemplateOrder& order)
{
    auto found = std::find_if(player.productionTemplates.begin(), player.productionTemplates.end(),
        [&](const auto& value) { return value.name == order.value.name; });
    if (order.remove) {
        if (found == player.productionTemplates.end()) return false;
        player.productionTemplates.erase(found);
        return true;
    }
    if (!production_template_valid(order.value)
        || (found == player.productionTemplates.end() && player.productionTemplates.size() >= 16)) return false;
    if (order.value.defaultForNewColonies)
        for (auto& value : player.productionTemplates) value.defaultForNewColonies = false;
    if (found == player.productionTemplates.end()) player.productionTemplates.push_back(order.value);
    else *found = order.value;
    return true;
}

bool apply_production_template(Planet& planet, const Player& player, const std::string& name)
{
    if (planet.owner != player.id) return false;
    const auto found = std::find_if(player.productionTemplates.begin(), player.productionTemplates.end(),
        [&](const auto& value) { return value.name == name; });
    if (found == player.productionTemplates.end() || !production_template_valid(*found)) return false;
    std::erase_if(planet.productionQueue, [](const auto& item) { return item.automation != ProductionAutomation::None; });
    planet.productionQueue.insert(planet.productionQueue.end(), found->items.begin(), found->items.end());
    return true;
}

void apply_default_production_template(const GameState& state, Planet& planet)
{
    const auto* player = find_player(state, planet.owner);
    if (!player) return;
    const auto found = std::find_if(player->productionTemplates.begin(), player->productionTemplates.end(),
        [](const auto& value) { return value.defaultForNewColonies; });
    if (found != player->productionTemplates.end()) (void)apply_production_template(planet, *player, found->name);
}

ColonyProductionResolution resolve_colony_production(const GameState& state, Planet& planet, bool hasShipyard, std::optional<bool> engineeringSupport)
{
    ColonyProductionResolution result;
    result.hasShipyard = hasShipyard;
    result.engineeringSupport=engineeringSupport.value_or(engineering_station_available(state,planet));
    planet.engineering.operational=planet.engineering.kind!=PlanetaryEngineeringKind::None
        && planet.engineering.work==kEngineeringWork && planet.engineering.strength>0
        && planet.owner && planet.population && result.engineeringSupport;
    if (planet.owner == 0) return result;
    const auto* player = find_player(state, planet.owner);
    const auto output = colony_output(planet);
    const bool researchActive = player && player->technology.researchActive;
    const auto requestedResearch = researchActive ? static_cast<std::uint32_t>(
        std::uint64_t(output) * player->technology.researchAllocationPercent / 100U) : 0U;
    const bool bootstrappingReceiver = planet.radar == PlanetaryRadarLevel::None
        && std::any_of(planet.productionQueue.begin(), planet.productionQueue.end(),
            [](const ProductionItem& item) { return item.kind == ProductionKind::LocalRadar; });
    // A remote settlement must always be able to bootstrap its local receiver,
    // including when the empire's research allocation is set to 100%.
    const auto allocated = bootstrappingReceiver && output > 0
        ? std::min(requestedResearch, output - 1) : requestedResearch;
    result.researchPoints = allocated;
    auto available = output - allocated;
    auto& queue = planet.productionQueue;
    std::vector<std::size_t> origins(queue.size());
    std::iota(origins.begin(), origins.end(), 0);
    std::vector<std::uint32_t> annualUsed(queue.size());
    planet.productionWaitingForMinerals = false;
    planet.productionWaitingForShipyard = false;
    bool stationExists = hasShipyard || find_orbital_station_at_planet(state, planet.id) != nullptr;
    const auto erase = [&](std::size_t index) {
        queue.erase(queue.begin() + index);
        origins.erase(origins.begin() + index);
    };
    const auto complete = [&](const ProductionItem& item, std::size_t origin, bool finishedBatch) {
        subtract_minerals(planet.minerals, production_item_mineral_cost(state, item));
        if (item.kind == ProductionKind::Factory) ++planet.industry;
        else if (item.kind == ProductionKind::Mine) ++planet.mines;
        else if (reconstruction_kind(item.kind)) {
            if(item.kind==ProductionKind::ReconstructFactory) { ++planet.industry; ++planet.warDamage.factoriesReconstructed; }
            else { ++planet.mines; ++planet.warDamage.minesReconstructed; }
            planet.warDamage.lastReconstructionTurn=state.turn+1;
        }
        else if(item.kind==ProductionKind::CleanupContamination) {
            auto& damage=planet.warDamage;
            damage.contamination-=std::min<unsigned>(damage.contamination,kContaminationCleanup);
            damage.lastCleanupTurn=state.turn+1;
            planet.observedHabitability.reset();
        }
        else if (item.kind == ProductionKind::ColonyDefense) ++planet.defenses;
        else if (item.kind == ProductionKind::LocalRadar) planet.radar = std::max(planet.radar, PlanetaryRadarLevel::Local);
        else if (item.kind == ProductionKind::PlanetaryRadar) planet.radar = PlanetaryRadarLevel::Full;
        else if (item.kind == ProductionKind::Terraforming) (void)terraform_planet(state, planet);
        else if (item.kind == ProductionKind::OrbitalStation) {
            stationExists = true;
            result.hasShipyard = !item.station || item.station->loadout.shipyard;
            result.engineeringSupport=item.station && item.station->loadout.hull>=OrbitalStationHullType::Starbase
                && item.station->loadout.shipyard;
        }
        result.completions.push_back({item, origin, finishedBatch,
            item.kind == ProductionKind::Factory || item.kind==ProductionKind::ReconstructFactory ? planet.industry : item.kind == ProductionKind::Mine || item.kind==ProductionKind::ReconstructMine ? planet.mines : item.kind == ProductionKind::ColonyDefense ? planet.defenses : 0U});
    };
    std::uint32_t engineeringUsed=0;
    std::size_t index = 0;
    while (index < queue.size()) {
        const auto origin = origins[index];
        if(engineering_kind(queue[index].kind)) {
            auto& e=planet.engineering;
            if(engineering_project_kind(queue[index].kind)!=e.kind || e.work>=kEngineeringWork) { erase(index); continue; }
            const auto work=advance_planetary_engineering(state,planet,available,result.engineeringSupport,
                kEngineeringWorkPerYear-engineeringUsed);
            engineeringUsed+=work; available-=work; queue[index].remainingCost=kEngineeringWork-e.work;
            if(e.work<kEngineeringWork && available>0 && engineeringUsed<kEngineeringWorkPerYear && result.engineeringSupport
                && planetary_engineering_available(state,planet.owner)) planet.productionWaitingForMinerals=true;
            if(e.work==kEngineeringWork) { result.completions.push_back({queue[index],origin,true,1}); erase(index); continue; }
            // Bounded annual assembly leaves surplus production for later items.
            // Missing infrastructure/materials hold manual queue priority.
            if(engineeringUsed<kEngineeringWorkPerYear && available>0) break;
            ++index; continue;
        }
        if(reconstruction_kind(queue[index].kind)) {
            const auto installed=queue[index].kind==ProductionKind::ReconstructFactory?planet.industry:planet.mines;
            const auto eligible=std::min(reconstruction_remaining(planet,queue[index].kind),
                std::uint64_t(std::numeric_limits<std::uint32_t>::max()-installed));
            if(!eligible) { erase(index); continue; } // Never charge for imaginary or already repaired ruins.
            queue[index].quantity=std::uint32_t(std::min(std::uint64_t(queue[index].quantity),eligible));
        }
        if(queue[index].kind==ProductionKind::CleanupContamination) {
            const auto remaining=cleanup_units_remaining(planet);
            if(!remaining) { erase(index); continue; }
            queue[index].quantity=std::min(queue[index].quantity,remaining);
        }
        if (queue[index].kind == ProductionKind::Research || queue[index].quantity == 0
            || (queue[index].kind == ProductionKind::OrbitalStation
                && (queue[index].station ? !station_construction_valid(state,planet,*queue[index].station) : stationExists))
            || (queue[index].kind == ProductionKind::LocalRadar && planet.radar != PlanetaryRadarLevel::None)
            || (queue[index].kind == ProductionKind::PlanetaryRadar && planet.radar == PlanetaryRadarLevel::Full)
            || (queue[index].kind == ProductionKind::ColonyDefense
                && ((planet.defenses >= kMaximumColonyDefenses && queue[index].automation == ProductionAutomation::None)
                    || !colony_defenses_available(state,planet.owner)))) { erase(index); continue; }
        const auto kind = queue[index].kind;
        const bool automatic = queue[index].automation != ProductionAutomation::None;
        if (automatic) {
            const auto rule = queue[index];
            while (annualUsed[origin] < rule.quantity) {
                if (kind == ProductionKind::ColonyDefense && planet.defenses >= kMaximumColonyDefenses) break;
                if (kind == ProductionKind::Terraforming
                    && ((rule.automation == ProductionAutomation::MinTerraform
                            && player_planet_habitability(state, planet.owner, planet, state.turn) >= 0)
                        || !next_terraforming_environment(state, planet.owner, planet))) break;
                ProductionItem work{kind, production_cost(kind), 0, ProductionAutomation::None, 1, true};
                // Auto rules cannot monopolize production while lacking minerals.
                if (!mineral_cargo_sufficient(planet.minerals, production_item_mineral_cost(state, work))) break;
                if (available == 0) break;
                const auto spent = std::min(available, work.remainingCost);
                work.remainingCost -= spent;
                available -= spent;
                if (work.remainingCost != 0) {
                    queue.insert(queue.begin() + index, work);
                    origins.insert(origins.begin() + index, origin);
                    ++index; // The unfinished normal build precedes its persistent rule.
                    break;
                }
                ++annualUsed[origin];
                complete(work, origin, false);
            }
            ++index;
            continue;
        }
        if (kind == ProductionKind::Terraforming && !next_terraforming_environment(state, planet.owner, planet)) {
            erase(index); // No eligible work remains: surplus manual terraforming is discarded without charge.
            continue;
        }
        if (kind == ProductionKind::ColonyShip && !result.hasShipyard) {
            planet.productionWaitingForShipyard = true;
            break;
        }
        const auto spent = std::min(available, queue[index].remainingCost);
        available -= spent;
        queue[index].remainingCost -= spent;
        if (queue[index].remainingCost != 0) break;
        if (!mineral_cargo_sufficient(planet.minerals, production_item_mineral_cost(state, queue[index]))) {
            planet.productionWaitingForMinerals = true;
            break;
        }
        const auto completed = queue[index];
        const bool finished = completed.quantity == 1;
        if (completed.autoGenerated && index + 1 < queue.size()
            && queue[index + 1].automation != ProductionAutomation::None && queue[index + 1].kind == kind)
            ++annualUsed[origins[index + 1]];
        complete(completed, origin, finished);
        if (finished) erase(index);
        else { --queue[index].quantity; queue[index].remainingCost = production_item_cost(state, queue[index]); }
    }
    if (researchActive) result.researchPoints += available;
    planet.engineering.operational=planet.engineering.kind!=PlanetaryEngineeringKind::None
        && planet.engineering.work==kEngineeringWork && planet.engineering.strength>0
        && planet.owner && planet.population && result.engineeringSupport;
    result.queueOrigins = std::move(origins);
    return result;
}

GameState planned_production_state(const GameState& state, const PlayerOrders& pending)
{
    auto result = planned_ship_design_state(state, pending);
    for (const auto& order : pending.orders) std::visit([&](const auto& value) {
        using T = std::decay_t<decltype(value)>;
        if constexpr (std::is_same_v<T, SetResearchAllocationOrder> || std::is_same_v<T, SetResearchPlanOrder>) {
            // Forecast settings must follow the research orders accepted by End Turn.
            const auto player=std::find_if(result.players.begin(),result.players.end(),
                [&](const auto& p){return p.id==pending.player;});
            if(player==result.players.end())return;
            if constexpr (std::is_same_v<T, SetResearchAllocationOrder>) {
                if(value.percent<=100)player->technology.researchAllocationPercent=value.percent;
            } else {
                const auto validField=[](ResearchField field){return std::size_t(field)<kResearchFieldCount;};
                if((value.active && !validField(value.focus)) || (!value.active && !value.queuedFocuses.empty())
                    || !std::all_of(value.queuedFocuses.begin(),value.queuedFocuses.end(),validField))return;
                player->technology.researchActive=value.active;
                if(value.active)player->technology.focus=value.focus;
                player->technology.queuedFocuses=value.queuedFocuses;
            }
        } else if constexpr (std::is_same_v<T, SetPlanetaryEngineeringOrder>) {
            const auto p=std::find_if(result.planets.begin(),result.planets.end(),[&](const auto& p){return p.id==value.colony && p.owner==pending.player;});
            if(p!=result.planets.end()) (void)apply_planetary_engineering_order(result,*p,value);
        } else if constexpr (std::is_same_v<T, QueueStationOrder>) {
            (void)queue_station_construction(result,pending.player,value);
        } else if constexpr (std::is_same_v<T, SetProductionTemplateOrder>) {
            const auto player = std::find_if(result.players.begin(), result.players.end(),
                [&](const auto& entry) { return entry.id == pending.player; });
            if (player != result.players.end()) (void)set_production_template(*player, value);
        } else if constexpr (std::is_same_v<T, QueueProductionBatchOrder> || std::is_same_v<T, ApplyProductionTemplateOrder>
            || std::is_same_v<T, QueueProductionOrder> || std::is_same_v<T, QueueShipDesignOrder>
            || std::is_same_v<T, ReorderProductionQueueOrder> || std::is_same_v<T, CancelProductionOrder>) {
            const auto found = std::find_if(result.planets.begin(), result.planets.end(),
                [&](const auto& entry) { return entry.id == value.colony && entry.owner == pending.player; });
            if (found == result.planets.end()) return;
            auto& colony = *found;
            std::erase_if(colony.productionQueue, [](const auto& item) { return item.kind == ProductionKind::Research; });
            auto& queue = colony.productionQueue;
            if constexpr (std::is_same_v<T, QueueProductionBatchOrder>) (void)apply_production_batch(result, colony, value);
            else if constexpr (std::is_same_v<T, ApplyProductionTemplateOrder>) {
                if (const auto* player = find_player(result, pending.player)) (void)apply_production_template(colony, *player, value.name);
            } else if constexpr (std::is_same_v<T, CancelProductionOrder>) {
                if (value.index < queue.size()) queue.erase(queue.begin() + value.index);
            } else if constexpr (std::is_same_v<T, ReorderProductionQueueOrder>) {
                if (value.fromIndex < queue.size() && value.toIndex < queue.size()) {
                    auto item = queue[value.fromIndex];
                    queue.erase(queue.begin() + value.fromIndex);
                    queue.insert(queue.begin() + value.toIndex, item);
                }
            } else if constexpr (std::is_same_v<T, QueueShipDesignOrder>) {
                if (const auto* design = resolve_ship_design_order(result, pending.player, value);
                    design && design->owner == pending.player && ship_design_valid(*design)
                    && colony_has_orbital_service(result, colony.id, pending.player, OrbitalStationModule::Shipyard))
                    queue.push_back({ProductionKind::ColonyShip, ship_design_cost(*design), design->id});
            } else if constexpr (std::is_same_v<T, QueueProductionOrder>) {
                if (engineering_kind(value.kind) || recovery_kind(value.kind) || value.kind == ProductionKind::Factory || value.kind == ProductionKind::Mine || value.kind == ProductionKind::Terraforming || value.kind == ProductionKind::ColonyDefense)
                    (void)apply_production_batch(result, colony, {colony.id, value.kind});
                else if (value.kind == ProductionKind::OrbitalStation && !find_orbital_station_at_planet(result, colony.id)
                    && std::none_of(queue.begin(), queue.end(), [](const auto& item) { return item.kind == ProductionKind::OrbitalStation; }))
                    queue.push_back({value.kind, kOrbitalDockCost});
                else if (value.kind == ProductionKind::ColonyShip
                    && colony_has_orbital_service(result, colony.id, pending.player, OrbitalStationModule::Shipyard)) {
                    const auto design = std::find_if(result.shipDesigns.begin(), result.shipDesigns.end(),
                        [&](const auto& candidate) { return candidate.owner == pending.player && ship_design_can_colonize(candidate); });
                    if (design != result.shipDesigns.end()) queue.push_back({value.kind, ship_design_cost(*design), design->id});
                }
            }
        }
    }, order);
    return result;
}

